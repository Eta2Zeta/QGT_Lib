def _write_json(path, value):
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2) + "\n")
    temporary.replace(path)


def expected_plot_files(n_bands):
    """The standard four band plots plus four QGT plots per band."""
    files = [
        "eigenvalue_surfaces.html", "degeneracy_heatmap.png",
        "eigenvalue_line_slider_ij.html", "eigenvalue_line_slider_ji.html",
    ]
    for band in range(n_bands):
        files.extend([
            f"qgt_eigenvalue_berry_component_heatmaps_band_{band}.png",
            f"qgt_component_surfaces_band_{band}.html",
            f"qgt_eigenvalue_berry_trace_surfaces_band_{band}.html",
            f"qgt_eigenvalue_berry_trace_heatmaps_band_{band}_xy.png",
        ])
    return files


def _source_hashes():
    names = [
        "qgt/plotting/minimal_planes.py", "qgt/workflows/eigen_2d.py", "qgt/workflows/qgt_2d.py",
        "qgt/plotting/bands_2d.py", "qgt/plotting/qgt_2d.py",
        "qgt/plotting/common.py", "qgt/kspace/paths.py", "qgt/utils.py",
    ]
    return {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
            for name in names}


def _input_hashes(dataset_dir):
    """Fingerprint every saved input used to render this dataset's figures."""
    names = [
        "meta.json", "summary.json", "meta_info.pkl", "ki.npy", "kj.npy",
        "bz_mask.npy", "eigenvalues.npy",
        *(key + ".npy" for key in _QGT_PLOT_COMPONENTS),
    ]
    return {name: hashlib.sha256((dataset_dir / name).read_bytes()).hexdigest()
            for name in names}


def _label_html(path, title):
    """Add context without changing the figures generated by library code."""
    source = path.read_text()
    banner = ('<div style="font:16px system-ui;padding:12px 20px">'
              + html.escape(title) + '</div>')
    source = source.replace("<body>", "<body>" + banner, 1)
    source = source.replace("<head>", "<head><title>" + html.escape(title)
                            + "</title>", 1)
    path.write_text(source)


def plot_dataset(dataset_dir, force=False):
    """Create/reuse all standard automatic figures in one saved dataset.

    The metadata pickle belongs to the local calculation and restores the
    exact Hamiltonian used for symmetry-path overlays. ``plots.json`` is
    written only after every expected figure exists and is nonempty.
    """
    dataset_dir = Path(relocate_legacy_path(dataset_dir)).resolve()
    meta = json.loads((dataset_dir / "meta.json").read_text())
    summary = json.loads((dataset_dir / "summary.json").read_text())
    n_bands = int(meta["n_bands"])
    files = expected_plot_files(n_bands)
    source_sha256 = _source_hashes()
    input_sha256 = _input_hashes(dataset_dir)
    marker = dataset_dir / "plots.json"
    if marker.exists() and not force:
        previous = json.loads(marker.read_text())
        if (previous.get("settings") == SETTINGS
                and previous.get("source_sha256") == source_sha256
                and previous.get("input_sha256") == input_sha256
                and previous.get("files") == files
                and all((dataset_dir / name).is_file()
                        and (dataset_dir / name).stat().st_size > 0
                        for name in files)):
            return {**previous, "status": "reused"}

    # An interrupted refresh must not look like a complete plot set.
    marker.unlink(missing_ok=True)
    with (dataset_dir / "meta_info.pkl").open("rb") as stream:
        saved_meta = pickle.load(stream)
    hamiltonian = saved_meta["Hamiltonian_Obj"]
    ki = np.load(dataset_dir / "ki.npy")
    kj = np.load(dataset_dir / "kj.npy")
    bz_mask = np.load(dataset_dir / "bz_mask.npy")
    eigenvalues = np.load(dataset_dir / "eigenvalues.npy")
    # The standard capping function mutates its input; keep raw energies intact.
    capped_eigenvalues = capping_eigenvalues(eigenvalues.copy(), z_limit=1000)
    eigenvalues_for_plot = capped_eigenvalues.copy()
    eigenvalues_for_plot[~bz_mask] = np.nan
    qgt = {key: np.load(dataset_dir / (key + ".npy"))
           for key in _QGT_PLOT_COMPONENTS}
    order = meta["order"]
    kk = meta["kk"]
    x_label, y_label = meta["coordinate_labels"][:2]
    variant = f" ({summary['variant']})" if summary.get("variant") else ""
    label = f"{summary['model']}{variant} | kz = {kk:.8g} ({summary['plane']})"
    common = {"results_dir": str(dataset_dir), "save_fig": True}
    overlay = {"hamiltonian": hamiltonian if order == "xyz" else None,
               "kk": kk, "order": order}
    heatmap_limits = {"zlim_berry": 1000, "zlim_percentile": 95}
    undefined_bands = []

    try:
        plot_eigenvalue_surfaces(
            ki, kj, eigenvalues_for_plot, dim=n_bands,
            z_limit=1000, stride_size=2, color_maps="default", norm=None,
            bands_to_plot=None, x_label=x_label, y_label=y_label,
            show=False, **common,
        )
        plot_degeneracy_heatmap(
            ki, kj, capped_eigenvalues, threshold=0.02,
            title=f"Band Degeneracy Map (full grid): {label}", sym_points=(order == "xyz"),
            hamiltonian=overlay["hamiltonian"], kk=kk,
            x_label=x_label, y_label=y_label, **common,
        )
        for axis_order in ("ij", "ji"):
            horizontal = x_label if axis_order == "ij" else y_label
            slider = y_label if axis_order == "ij" else x_label
            plot_eigenvalue_line_slider(
                ki, kj, eigenvalues_for_plot, axis_order=axis_order,
                first_axis_label=x_label, second_axis_label=y_label,
                bands_to_plot=None,
                title=f"Eigenvalues vs {horizontal}; slider: {slider} | {label}",
                show=False, **common,
            )

        for band in range(n_bands):
            undefined = not np.isfinite(qgt["trace"][band]).any()
            note = "; undefined single-band QGT (degenerate bands)" if undefined else ""
            if undefined:
                undefined_bands.append(band)
            band_label = f"{label} | Band {band + 1}{note}"
            # The existing Plotly surface code handles NaNs as empty surfaces.
            # Silence only its expected extrema warnings, retaining missing data.
            with warnings.catch_warnings():
                warnings.filterwarnings("ignore", message="All-NaN slice encountered",
                                        category=RuntimeWarning)
                plot_qgt_eigenvalue_berry_component_heatmaps(
                    ki, kj, eigenvalues_for_plot, qgt["g_xy_imag"][band],
                    qgt["g_xz_imag"][band], qgt["g_yz_imag"][band],
                    eigenvalue_band=band, title=band_label,
                    **heatmap_limits, **common, **overlay,
                )
                plot_qgt_component_surfaces(
                    ki, kj, qgt["g_xx"][band], qgt["g_xy_real"][band],
                    qgt["g_xy_imag"][band], qgt["g_yy"][band],
                    stride_size=2,
                    filename=f"qgt_component_surfaces_band_{band}.html",
                    show=False, order=order, **common,
                )
                plot_qgt_eigenvalue_berry_trace_surfaces(
                    ki, kj, eigenvalues_for_plot, qgt["g_xy_imag"][band],
                    qgt["trace"][band], eigenvalue_band=band,
                    title=f"Surface Results: {band_label}",
                    filename=f"qgt_eigenvalue_berry_trace_surfaces_band_{band}.html",
                    show=False, order=order, **common,
                )
                plot_qgt_eigenvalue_berry_trace_heatmaps(
                    ki, kj, eigenvalues_for_plot, qgt["g_xy_imag"][band],
                    qgt["trace"][band], eigenvalue_band=band,
                    title=f"2D Results: {band_label}",
                    **heatmap_limits, **common, **overlay,
                )
            for prefix in ("qgt_component_surfaces", "qgt_eigenvalue_berry_trace_surfaces"):
                _label_html(dataset_dir / f"{prefix}_band_{band}.html", band_label)
        for name in files[:4]:
            if name.endswith(".html"):
                _label_html(dataset_dir / name, label)
    finally:
        plt.close("all")

    missing = [name for name in files if not (dataset_dir / name).is_file()
               or (dataset_dir / name).stat().st_size == 0]
    if missing:
        raise RuntimeError(f"Incomplete plots in {dataset_dir}: {missing}")
    report = {
        "status": "complete", "dataset_dir": str(dataset_dir),
        "model": summary["model"], "plane": summary["plane"], "kz": kk,
        "n_bands": n_bands, "files": files,
        "undefined_qgt_bands": undefined_bands,
        "settings": SETTINGS, "source_sha256": source_sha256,
        "input_sha256": input_sha256,
        "sources": ["qgt.workflows.eigen_2d.calculation_2d",
                    "qgt.workflows.qgt_2d.calculate_2d_all_bands"],
    }
    _write_json(marker, report)
    return report


CROSSING_SOURCES = (
    "qgt/hamiltonians/minimal_models/crossings.py", "qgt/plotting/crossings.py",
    "qgt/plotting/qgt_2d.py", "qgt/plotting/minimal_planes.py",
)


def crossing_plot_files(n_bands):
    return ["band_crossings.json", *(f"qgt_eigenvalue_berry_component_heatmaps_band_{band}_crossings.png"
                                     for band in range(n_bands))]


def _saved_hamiltonian(dataset_dir, ki, kj, kk, bz_mask, eigenvalues, samples=64):
    """The dataset's pickled Hamiltonian, checked against its saved eigenvalues.

    Objects pickled by an older version of a class lack attributes for terms added to
    the class later (e.g. SG11's lamb_z_xz_add); those terms were absent, so they are
    set to 0. The model must then reproduce the saved eigenvalues.
    """
    with (dataset_dir / "meta_info.pkl").open("rb") as stream:
        hamiltonian = pickle.load(stream)["Hamiltonian_Obj"]
    missing = [name for name in inspect.signature(type(hamiltonian).__init__).parameters
               if name not in ("self", "args", "kwargs") and not hasattr(hamiltonian, name)]
    for name in missing:
        setattr(hamiltonian, name, 0)
    rows, cols = np.nonzero(bz_mask)
    pick = np.random.default_rng(0).choice(len(rows), min(samples, len(rows)), replace=False)
    worst = max(np.max(np.abs(np.linalg.eigvalsh(hamiltonian.compute_static(ki[i, j], kj[i, j], kk))
                              - np.sort(eigenvalues[i, j])))
                for i, j in zip(rows[pick], cols[pick]))
    if worst > 1e-8:
        raise ValueError(f"The saved Hamiltonian in {dataset_dir} (missing {missing} set to 0) does not "
                         f"reproduce the saved eigenvalues (difference {worst:.2e})")
    return hamiltonian


def plot_dataset_crossings(dataset_dir, force=False, output_dir=None):
    """Find the exact band crossings in a saved dataset's plane and redraw its band and
    Berry-component heatmaps with them overlaid.

    Writes ``band_crossings.json`` and ``qgt_eigenvalue_berry_component_heatmaps_band_<n>_crossings.png``
    into output_dir (default: the dataset folder); the saved arrays and the standard figures
    are not touched. ``crossings_plots.json`` records what was made and lets an unchanged
    dataset be skipped.
    """
    from qgt.hamiltonians.minimal_models.crossings import find_band_crossings

    dataset_dir = Path(relocate_legacy_path(dataset_dir)).resolve()
    output_dir = Path(output_dir or dataset_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    meta = json.loads((dataset_dir / "meta.json").read_text())
    summary = json.loads((dataset_dir / "summary.json").read_text())
    n_bands = int(meta["n_bands"])
    files = crossing_plot_files(n_bands)
    source_sha256 = {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest() for name in CROSSING_SOURCES}
    input_sha256 = _input_hashes(dataset_dir)
    marker = output_dir / "crossings_plots.json"
    if marker.exists() and not force:
        previous = json.loads(marker.read_text())
        if (previous.get("source_sha256") == source_sha256 and previous.get("input_sha256") == input_sha256
                and all((output_dir / name).is_file() for name in files)):
            return {**previous, "status": "reused"}
    marker.unlink(missing_ok=True)

    kk, order = meta["kk"], meta["order"]
    if order != "xyz":
        raise ValueError(f"Crossing overlays need kx-ky planes (order 'xyz'), not {order!r}")
    ki = np.load(dataset_dir / "ki.npy")
    kj = np.load(dataset_dir / "kj.npy")
    bz_mask = np.load(dataset_dir / "bz_mask.npy")
    saved_eigenvalues = np.load(dataset_dir / "eigenvalues.npy")
    hamiltonian = _saved_hamiltonian(dataset_dir, ki, kj, kk, bz_mask, saved_eigenvalues)
    crossings = find_band_crossings(hamiltonian, kz=kk, line_samples=200)
    components = [c.to_dict() for c in crossings]
    _write_json(output_dir / "band_crossings.json",
                {"model": summary["model"], "plane": summary["plane"], "kz": kk, "components": components})

    eigenvalues = capping_eigenvalues(saved_eigenvalues.copy(), z_limit=1000)
    eigenvalues[~bz_mask] = np.nan
    qgt = {key: np.load(dataset_dir / (key + ".npy")) for key in ("g_xy_imag", "g_xz_imag", "g_yz_imag")}
    variant = f" ({summary['variant']})" if summary.get("variant") else ""
    label = f"{summary['model']}{variant} | kz = {kk:.8g} ({summary['plane']})"
    try:
        for band in range(n_bands):
            with warnings.catch_warnings():
                warnings.filterwarnings("ignore", message="All-NaN slice encountered", category=RuntimeWarning)
                plot_qgt_eigenvalue_berry_component_heatmaps(
                    ki, kj, eigenvalues, qgt["g_xy_imag"][band], qgt["g_xz_imag"][band], qgt["g_yz_imag"][band],
                    eigenvalue_band=band, title=f"{label} | Band {band + 1} | exact band crossings overlaid",
                    zlim_berry=1000, zlim_percentile=95, results_dir=str(output_dir), save_fig=True,
                    hamiltonian=hamiltonian, kk=kk, order=order, crossings=crossings,
                    filename=f"qgt_eigenvalue_berry_component_heatmaps_band_{band}_crossings.png",
                )
    finally:
        plt.close("all")
    report = {"status": "complete", "dataset_dir": str(dataset_dir), "output_dir": str(output_dir),
              "model": summary["model"],
              "plane": summary["plane"], "kz": kk, "n_bands": n_bands, "files": files,
              "components": [{key: c[key] for key in ("pair", "dimension", "exact", "description", "max_gap")}
                             for c in components],
              "source_sha256": source_sha256, "input_sha256": input_sha256}
    _write_json(marker, report)
    return report


