_NODE_FAMILY = {"MinimalHam" + model: family
                for family, models in _NODE_FAMILY_MODELS.items() for model in models}


def _symmetry_nodes_html(model_name):
    """Render the notes' full 3D zero sets, independent of the plotted kz slice.

    Note 1–3 supplies the axial constraints and model/orbit assignments.
    Note 2–6 selects F-dominant rows; Note 2–2–1, Table 1 supplies their
    central mirror-enforced common F zeros. No numerical data are changed.
    """
    family = _NODE_FAMILY.get(model_name)
    if family is None:
        return ""

    kx, ky, kz = (f'<i>k</i><sub>{axis}</sub>' for axis in 'xyz')
    px, py, pz = (f'{{{coordinate} = 0}}' for coordinate in (kx, ky, kz))
    ox, oy, oz = (f'<i>Ω</i><sub>{axis}</sub>' for axis in 'xyz')

    def union(*loci):
        return ' ∪ '.join(loci)

    def intersection(*loci):
        return '(' + ' ∩ '.join(loci) + ')'

    def angular_loci(angles, symbol='V'):
        # Each V/ell denotes a plane/line in 3D, with the note's conventions.
        return union(*(f'{symbol}<sub>{angle}°</sub>' for angle in angles))

    def rotated_loci(angles, symbol='V'):
        values = ', '.join(f'{angle}°' for angle in angles)
        return f'{symbol}<sub>θ</sub>, θ ∈ {{{values}}}'

    x_axis = intersection(py, pz)
    y_axis = intersection(px, pz)
    z_axis = intersection(px, py)
    coordinate_axes = union(x_axis, y_axis, z_axis)
    coordinate_planes = union(px, py)
    diagonal_planes = union(f'{{{kx} = {ky}}}', f'{{{kx} = −{ky}}}')
    four_planes = union(coordinate_planes, diagonal_planes)
    u0, u30 = (0, 60, 120), (30, 90, 150)
    six_angles = (0, 30, 60, 90, 120, 150)
    none = '<span class="math-word">None required</span>'

    # Full 3D zero sets for Omega_x, Omega_y, Omega_z, and the whole vector.
    # Parentheses keep unions of axes distinct from intersections of planes.
    axial_zeros = {
        '1': (union(py, y_axis), none, union(py, y_axis), none),
        '2': (union(py, pz), union(px, pz), coordinate_planes, coordinate_axes),
        '3x': (none, coordinate_planes, union(px, pz), none),
        '3y': (coordinate_planes, none, union(py, pz), none),
        '4': (union(pz, z_axis), union(pz, z_axis), z_axis, z_axis),
        '5': (union(py, pz), union(px, pz), four_planes,
              union(z_axis, intersection(pz, f'({four_planes})'))),
        '6c': (union(py, pz), union(px, pz), coordinate_planes, coordinate_axes),
        '6d': (union(px, pz), union(py, pz), diagonal_planes,
               union(z_axis, intersection(pz, f'({diagonal_planes})'))),
        '7a': (union(py, y_axis), z_axis,
               union(angular_loci(u0), angular_loci(u30, 'ℓ')), z_axis),
        '7b': (z_axis, union(px, x_axis),
               union(angular_loci(u30), angular_loci(u0, 'ℓ')), z_axis),
        '8': (z_axis, z_axis, union(pz, z_axis), z_axis),
        '9': (union(py, pz), union(px, pz), angular_loci(six_angles),
              union(z_axis, angular_loci(six_angles, 'ℓ'))),
        '10a': (coordinate_planes, z_axis, union(pz, angular_loci(u0)), z_axis),
        '10b': (z_axis, coordinate_planes, union(pz, angular_loci(u30)), z_axis),
    }
    # Common mirror zeros of F, with no slice restriction or harmonic extras.
    # SG 223 retains F + G at equal order despite sharing axial family 6d.
    f_zeros = {
        '2': union(px, py, pz),
        '4': pz,
        '5': union(four_planes, pz),
        '6c': union(px, py, pz),
        '6d': union(diagonal_planes, pz),
        '7a': angular_loci(u0),
        '7b': angular_loci(u30),
        '8': '<span class="math-word">No mirror-enforced common zero plane</span>',
        '10a': angular_loci(u0),
        '10b': angular_loci(u30),
    }
    f_dominant = (family in f_zeros and model_name != "MinimalHamSG223_2a")
    f_header = ('<th scope="col">F contribution<br>Whole-vector zero set</th>'
                if f_dominant else '')
    f_cell = (f'<td class="f-zero-set"><span class="math">'
              f'{f_zeros[family]}</span></td>' if f_dominant else '')
    labels = (ox, oy, oz, '<b>Ω</b>')
    rows = ''.join(
        f'<tr><th scope="row"><span class="math">{component} = 0</span></th>'
        f'<td><span class="math">{locus}</span></td>'
        + ((f_cell if index == 3 else '<td></td>') if f_dominant else '') + '</tr>'
        for index, (component, locus) in enumerate(zip(labels, axial_zeros[family]))
    )
    rotated = []
    if family in ('5', '6c', '6d'):
        first, second = ('−', '+') if family == '6c' else ('+', '−')
        rotated = [f'{kx} = {ky} ⇒ {ox} {first} {oy} = 0',
                   f'{kx} = −{ky} ⇒ {ox} {second} {oy} = 0']
    elif family in ('7a', '7b', '9', '10a', '10b'):
        u = u0 if family in ('7a', '10a') else u30
        if family == '9':
            u = six_angles
        a = tuple(angle for angle in six_angles if angle not in u)
        rotated.append(f'{rotated_loci(u)}: Ω<sub>θ</sub> = 0')
        if family in ('7a', '7b', '10a', '10b'):
            # Family 7 has basal rotation axes; family 10 has vertical planes.
            symbol = 'ℓ' if family in ('7a', '7b') else 'V'
            rotated.append(f'{rotated_loci(a, symbol)}: Ω<sub>θ+90°</sub> = 0')

    extra = (
        '<p class="f-scope">The F entry in the full-vector row gives common '
        'zeros of all three F components from central unitary mirrors '
        '(Note 2–2–1, Table 1). F leads G near Γ for this family with generic '
        'coefficients (Note 2–6); G can still contribute at finite momentum.</p>'
        if f_dominant else ''
    )
    if rotated:
        extra += ('<p class="rotated"><strong>Rotated components:</strong><br>'
                  + '<br>'.join(f'<span class="math">{rule}</span>' for rule in rotated)
                  + '</p>')
    if family in ('7a', '7b', '9', '10a', '10b'):
        extra += (
            '<details class="notation"><summary>Plane, line, and component notation</summary>'
            f'<p><span class="math">V<sub>θ</sub> = {{−{kx} sin θ + {ky} cos θ = 0}}</span> '
            'is a vertical plane; '
            f'<span class="math">ℓ<sub>θ</sub> = V<sub>θ</sub> ∩ {pz}</span> '
            'is its basal line. Angles are measured from the '
            f'<span class="math">{kx}</span> axis.<br>'
            f'<span class="math">Ω<sub>θ</sub> = {ox} cos θ + {oy} sin θ</span><br>'
            f'<span class="math">Ω<sub>θ+90°</sub> = −{ox} sin θ + {oy} cos θ</span>'
            '</p></details>'
        )
    family_label = {'7a': '7, δ = 0°', '7b': '7, δ = 30°'}.get(family, family)
    return (
        '<aside class="symmetry-nodes"><h3>Expected symmetry nodes (3D)</h3>'
        f'<p class="source">Note 1–3 · family {family_label} · '
        '<span class="math"><i>J</i> ∥ <i>z</i></span></p>'
        '<table><thead><tr><th scope="col">Berry curvature</th>'
        f'<th scope="col">Axial-vector zero set</th>{f_header}</tr></thead>'
        f'<tbody>{rows}</tbody></table>{extra}</aside>'
    )


def _sg11_added_terms_html(params):
    """Show the saved added Hamiltonian terms with their actual coefficients."""
    kx = '<i>k</i><sub>x</sub>'
    ky = '<i>k</i><sub>y</sub>'
    kz = '<i>k</i><sub>z</sub>'
    tau_x = '<i>τ</i><sub>x</sub>'
    tau_y_sigma_z = '<i>τ</i><sub>y</sub> <i>σ</i><sub>z</sub>'
    bases = (
        ('t3_add', f'cos {kx} cos({ky}/2) {tau_x}'),
        ('lamb_z_add', f'cos {kz} cos({ky}/2) {tau_y_sigma_z}'),
        ('lamb_z_xz_add', f'sin {kx} sin {kz} cos({ky}/2) {tau_y_sigma_z}'),
    )
    rows = []
    for name, basis in bases:
        coefficient = params.get(name, 0)
        if coefficient == 0:
            continue
        sign = '−' if coefficient < 0 else '+'
        prefix = 'δ<i>H</i> = ' + ('− ' if coefficient < 0 else '') if not rows else sign
        rows.append(
            '<div class="math"><span class="term-label">' + prefix + '</span>'
            + f'{abs(coefficient):.8g} {basis}</div>'
        )
    if not rows:
        return ''
    return ('<p class="added-terms">Added symmetry-allowed terms (Note 3–3):</p>'
            '<div class="added-hamiltonian">' + ''.join(rows) + '</div>')


# SG11 is calculated as the original minimal model and as the default with the three
# symmetry-allowed terms of Note 3-3 added.
_SG11_ADDED = ("t3_add", "lamb_z_add", "lamb_z_xz_add")


def _sg11_variant(params):
    """(order, label) of an SG11 parameter set: the original model first, then added terms."""
    added = [float(params.get(name) or 0) for name in _SG11_ADDED]
    if not any(added):
        return 0, "original minimal model"
    if all(added):
        return 1, "added terms (default)"
    return 2, "some added terms"


def _variant_order(item):
    if item["model"] != "MinimalHamSG11_2a2b2c2d":
        return 0
    meta = Path(relocate_legacy_path(item["dataset_dir"])) / "meta.json"
    if not meta.is_file():  # a dataset being replaced; write_gallery skips it
        return 0
    return _sg11_variant(json.loads(meta.read_text()).get("hamiltonian_params", {}))[0]


def gallery_order(results):
    """Models in their first-seen order; within a model, the original first, then planes."""
    first = {}
    for position, item in enumerate(results):
        first.setdefault(item["model"], position)
    return sorted(results, key=lambda item: (first[item["model"]], _variant_order(item), item["kz"]))


def _crossings_html(dataset_dir, link):
    """List of the exact band crossings saved for one dataset, plus links to every band's overlay."""
    path = dataset_dir / "crossings_plots.json"
    if not path.exists():
        return '<p class="note">No band crossings computed for this dataset.</p>'
    report = json.loads(path.read_text())
    names = {"2-3": "Bands 2–3", "1-2,3-4": "Bands 1–2 and 3–4"}
    rows = []
    for pair in ("1-2,3-4", "2-3"):
        items = [c for c in report["components"] if c["pair"] == pair]
        if not items:
            rows.append(f'<li><b>{names[pair]}</b>: no crossing in this plane</li>')
            continue
        entries = "".join(
            f'<li>{html.escape(c["description"].split("  [")[0][:220])} '
            f'<span class="tag">{"exact" if c["exact"] else "exact equation, sampled"}</span></li>'
            for c in items)
        rows.append(f'<li><b>{names[pair]}</b><ul>{entries}</ul></li>')
    bands = " ".join(
        f'<a href="{link(name)}">Band {band + 1}</a>'
        for band, name in enumerate(n for n in report["files"] if n.endswith("_crossings.png")))
    return ('<div class="crossings"><h3>Band crossings in this plane</h3><ul>' + "".join(rows) + "</ul>"
            f'<p class="band-links">Overlay for every band: {bands}</p></div>')


